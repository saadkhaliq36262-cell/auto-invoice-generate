/**
 * Demo Limit and Developer Access Manager for AutoInvoice Pro
 */
class DemoManager {
  static MAX_DEMO_INVOICES = 2;
  static STORAGE_KEY = 'agy_demo_invoice_count';
  static ADMIN_KEY = 'agy_admin_mode';
  static FIVERR_URL = 'https://www.fiverr.com/saadkhaliq36262'; // Configurable Fiverr Profile/Gig URL

  /**
   * Initialize Demo Manager & check for secret developer bypass in URL
   */
  static init() {
    if (typeof window === 'undefined') return;

    // Check URL parameters for discrete developer bypass (?admin=true, ?dev=1, ?access=saad, etc.)
    try {
      const params = new URLSearchParams(window.location.search);
      const isDevParam = params.get('admin') === 'true' || 
                         params.get('admin') === '1' || 
                         params.get('admin') === 'saad' ||
                         params.get('dev') === '1' || 
                         params.get('dev') === 'true' ||
                         params.get('access') === 'saad';

      if (isDevParam) {
        localStorage.setItem(this.ADMIN_KEY, 'true');
        // Clean URL parameter without page reload
        const cleanUrl = window.location.protocol + "//" + window.location.host + window.location.pathname;
        window.history.replaceState({ path: cleanUrl }, '', cleanUrl);
      }
    } catch (e) {
      console.warn('Could not read URL params for admin check', e);
    }
  }

  /**
   * Check if current user is owner/admin/developer
   * @returns {boolean}
   */
  static isAdmin() {
    try {
      if (typeof localStorage === 'undefined') return false;
      return localStorage.getItem(this.ADMIN_KEY) === 'true';
    } catch (e) {
      return false;
    }
  }

  /**
   * Enable developer mode programmatically (accessible via window.enableDevMode() in console)
   */
  static enableDevMode() {
    try {
      localStorage.setItem(this.ADMIN_KEY, 'true');
      console.log('⚡ Developer Unlimited Access enabled.');
      return true;
    } catch (e) {
      return false;
    }
  }

  /**
   * Disable developer mode (for testing demo limit behavior)
   */
  static disableDevMode() {
    try {
      localStorage.removeItem(this.ADMIN_KEY);
      console.log('Visitor Demo mode enabled.');
      return true;
    } catch (e) {
      return false;
    }
  }

  /**
   * Get current number of invoices generated by this visitor
   * @returns {number}
   */
  static getUsageCount() {
    try {
      if (typeof localStorage === 'undefined') return 0;
      const count = localStorage.getItem(this.STORAGE_KEY);
      return count ? parseInt(count, 10) : 0;
    } catch (e) {
      return 0;
    }
  }

  /**
   * Increment demo usage by 1 (only for non-admin visitors)
   * @returns {number} New usage count
   */
  static incrementUsage() {
    if (this.isAdmin()) {
      return 0; // Admins have unlimited access, never incremented
    }

    try {
      const current = this.getUsageCount();
      const updated = current + 1;
      localStorage.setItem(this.STORAGE_KEY, updated.toString());
      return updated;
    } catch (e) {
      console.error('Error saving demo usage count:', e);
      return this.getUsageCount();
    }
  }

  /**
   * Check if the visitor has reached the 2-invoice limit
   * @returns {boolean}
   */
  static isLimitReached() {
    if (this.isAdmin()) return false;
    return this.getUsageCount() >= this.MAX_DEMO_INVOICES;
  }

  /**
   * Get remaining free invoices count
   * @returns {number}
   */
  static getRemainingCount() {
    if (this.isAdmin()) return Infinity;
    return Math.max(0, this.MAX_DEMO_INVOICES - this.getUsageCount());
  }

  /**
   * Reset demo count for local testing
   */
  static resetDemoCount() {
    try {
      localStorage.removeItem(this.STORAGE_KEY);
    } catch (e) {}
  }
}

// Global console helper for owner
if (typeof window !== 'undefined') {
  window.enableDevMode = () => {
    DemoManager.enableDevMode();
    if (typeof updateDemoBadge === 'function') updateDemoBadge();
    if (typeof showToast === 'function') showToast('⚡ Developer Unlimited Access Enabled', 'success');
  };
  window.disableDevMode = () => {
    DemoManager.disableDevMode();
    if (typeof updateDemoBadge === 'function') updateDemoBadge();
    if (typeof showToast === 'function') showToast('Visitor Demo Mode Active', 'info');
  };
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { DemoManager };
}
